document.addEventListener('DOMContentLoaded',()=>{
 const root=document.querySelector('.ll-live-header');if(!root)return;
 const dropdowns=[...root.querySelectorAll('details')];
 dropdowns.forEach(d=>d.addEventListener('toggle',()=>{if(d.open)dropdowns.filter(other=>other!==d).forEach(other=>other.open=false)}));
 document.addEventListener('click',e=>dropdowns.forEach(d=>{if(d.open&&!d.contains(e.target))d.open=false}));
 root.addEventListener('keydown',e=>{if(e.key==='Escape'){const open=dropdowns.find(d=>d.open);if(open){open.open=false;open.querySelector('summary').focus()}}});
 // Directory group headings are generated by its existing presentation script.
 // Resolve category links after that script has created the anchor targets.
 const scrollToCategory=()=>{const hash=location.hash.slice(1);if(hash){let id;try{id=decodeURIComponent(hash)}catch{return}document.getElementById(id)?.scrollIntoView({block:'start'})}};
 if(location.pathname.endsWith('businesses.html'))scrollToCategory();
});
